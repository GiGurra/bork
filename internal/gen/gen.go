// Package gen lowers a checked bork package to Go source.
//
// The output is a lowering, not a one-to-one translation: bork is
// expression-oriented, so `if` and blocks that produce values become Go
// statements writing to temporaries. Go code is built with go/ast and
// printed with go/printer, so it is always syntactically valid.
package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/printer"
	"go/token"
	"strconv"

	"github.com/GiGurra/bork/internal/check"
	"github.com/GiGurra/bork/internal/syntax"
)

// Package generates a Go `package main` source file.
func Package(files []*syntax.File, info *check.Info) ([]byte, error) {
	g := &gen{info: info}
	var decls []ast.Decl
	for _, f := range files {
		for _, fd := range f.Funcs {
			decls = append(decls, g.funcDecl(fd))
		}
	}
	if g.usesFmt {
		imp := &ast.GenDecl{Tok: token.IMPORT, Specs: []ast.Spec{
			&ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote("fmt")}},
		}}
		decls = append([]ast.Decl{imp}, decls...)
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by bork. DO NOT EDIT.\n\npackage main\n")
	fset := token.NewFileSet()
	for _, d := range decls {
		buf.WriteString("\n")
		if err := printer.Fprint(&buf, fset, d); err != nil {
			return nil, fmt.Errorf("printing generated Go: %w", err)
		}
		buf.WriteString("\n")
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated Go is invalid (compiler bug): %w\n%s", err, buf.String())
	}
	return out, nil
}

type gen struct {
	info    *check.Info
	tmp     int
	usesFmt bool
}

// goReserved holds names a bork identifier may not use verbatim in Go:
// Go keywords, predeclared identifiers, and imported package names.
var goReserved = map[string]bool{}

func init() {
	for _, s := range []string{
		"break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough",
		"for", "func", "go", "goto", "if", "import", "interface", "map", "package", "range",
		"return", "select", "struct", "switch", "type", "var",
		"any", "append", "bool", "byte", "cap", "clear", "close", "comparable", "complex",
		"complex64", "complex128", "copy", "delete", "error", "false", "float32", "float64",
		"imag", "int", "int8", "int16", "int32", "int64", "iota", "len", "make", "max", "min",
		"new", "nil", "panic", "print", "println", "real", "recover", "rune", "string", "true",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"fmt", "init",
	} {
		goReserved[s] = true
	}
}

// name maps a bork identifier to a Go identifier. bork identifiers
// cannot start with '_', so temporaries ('_tN') never collide.
func name(s string) *ast.Ident {
	if goReserved[s] {
		return ast.NewIdent(s + "_")
	}
	return ast.NewIdent(s)
}

func (g *gen) newTmp() *ast.Ident {
	g.tmp++
	return ast.NewIdent("_t" + strconv.Itoa(g.tmp))
}

func goType(t check.Type) ast.Expr {
	switch t {
	case check.Int:
		return ast.NewIdent("int64")
	case check.Bool:
		return ast.NewIdent("bool")
	case check.String:
		return ast.NewIdent("string")
	}
	panic(fmt.Sprintf("no Go type for %s", t))
}

func (g *gen) funcDecl(fd *syntax.FuncDecl) *ast.FuncDecl {
	fn := g.info.Funcs[fd.Name]
	g.tmp = 0
	ftype := &ast.FuncType{Params: &ast.FieldList{}}
	for i, p := range fd.Params {
		ftype.Params.List = append(ftype.Params.List, &ast.Field{
			Names: []*ast.Ident{name(p.Name)},
			Type:  goType(fn.Params[i]),
		})
	}
	var body []ast.Stmt
	if fn.Result == check.Unit {
		body = g.blockInto(fd.Body, nil)
	} else {
		ftype.Results = &ast.FieldList{List: []*ast.Field{{Type: goType(fn.Result)}}}
		body = g.blockReturn(fd.Body)
	}
	goName := name(fd.Name)
	if fd.Name == "main" {
		goName = ast.NewIdent("main")
	}
	return &ast.FuncDecl{Name: goName, Type: ftype, Body: &ast.BlockStmt{List: body}}
}

// value lowers an expression whose result is needed. It returns the
// statements to run first and the Go expression holding the result.
// The expression is nil when e never produces a value (type Never).
func (g *gen) value(e syntax.Expr) ([]ast.Stmt, ast.Expr) {
	t := g.info.Types[e]
	switch e := e.(type) {
	case *syntax.IntLit:
		return nil, &ast.BasicLit{Kind: token.INT, Value: strconv.FormatInt(g.info.IntValues[e], 10)}
	case *syntax.StringLit:
		return nil, &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(e.Value)}
	case *syntax.BoolLit:
		return nil, ast.NewIdent(strconv.FormatBool(e.Value))
	case *syntax.Ident:
		return nil, name(e.Name)
	case *syntax.Unary:
		stmts, x := g.value(e.X)
		if x == nil {
			return stmts, nil
		}
		op := token.SUB
		if e.Op == syntax.Not {
			op = token.NOT
		}
		return stmts, &ast.UnaryExpr{Op: op, X: paren(x)}
	case *syntax.Binary:
		return g.binary(e)
	case *syntax.Call:
		stmts, args := g.values(e.Args)
		if args == nil {
			return stmts, nil
		}
		call := g.callExpr(e, args)
		if t == check.Never {
			return append(stmts, &ast.ExprStmt{X: call}), nil
		}
		return stmts, call
	case *syntax.If:
		if t == check.Never || t == check.Unit {
			return g.effect(e), nil
		}
		res := g.newTmp()
		stmts := []ast.Stmt{varDecl(res, goType(t))}
		return append(stmts, g.ifStmt(e, res)...), res
	case *syntax.Block:
		if len(e.Stmts) == 0 && e.Tail != nil {
			return g.value(e.Tail)
		}
		if t == check.Never || t == check.Unit {
			return g.effect(e), nil
		}
		res := g.newTmp()
		return []ast.Stmt{varDecl(res, goType(t)), &ast.BlockStmt{List: g.blockInto(e, res)}}, res
	case *syntax.Return:
		return g.returnStmt(e), nil
	}
	panic(fmt.Sprintf("unhandled expression %T", e))
}

// values lowers several expressions that are evaluated left to right,
// as in a call's arguments. If a later expression needs statements to
// run first, earlier results are saved in temporaries so evaluation
// order is preserved. Returns nil expressions if any one never
// produces a value.
func (g *gen) values(es []syntax.Expr) ([]ast.Stmt, []ast.Expr) {
	var out []ast.Stmt
	xs := []ast.Expr{}
	for _, e := range es {
		stmts, x := g.value(e)
		if len(stmts) > 0 {
			for j := range xs {
				if !stable(xs[j]) {
					t := g.newTmp()
					out = append(out, define(t, xs[j]))
					xs[j] = t
				}
			}
			out = append(out, stmts...)
		}
		if x == nil {
			return out, nil
		}
		xs = append(xs, x)
	}
	return out, xs
}

// stable reports whether evaluating x later gives the same result:
// literals and identifiers (bork bindings are immutable).
func stable(x ast.Expr) bool {
	switch x.(type) {
	case *ast.BasicLit, *ast.Ident:
		return true
	}
	return false
}

var binaryOps = map[syntax.Kind]token.Token{
	syntax.Plus: token.ADD, syntax.Minus: token.SUB, syntax.Star: token.MUL,
	syntax.Slash: token.QUO, syntax.Pct: token.REM,
	syntax.Eq: token.EQL, syntax.NotEq: token.NEQ,
	syntax.Lt: token.LSS, syntax.LtEq: token.LEQ, syntax.Gt: token.GTR, syntax.GtEq: token.GEQ,
	syntax.AndAnd: token.LAND, syntax.OrOr: token.LOR,
}

func (g *gen) binary(e *syntax.Binary) ([]ast.Stmt, ast.Expr) {
	if e.Op == syntax.AndAnd || e.Op == syntax.OrOr {
		sx, x := g.value(e.X)
		if x == nil {
			return sx, nil
		}
		sy, y := g.value(e.Y)
		if len(sy) == 0 && y != nil {
			return sx, &ast.BinaryExpr{X: paren(x), Op: binaryOps[e.Op], Y: paren(y)}
		}
		// The right side needs statements: run them only when the left
		// side does not already decide the result.
		res := g.newTmp()
		var cond ast.Expr = res
		if e.Op == syntax.OrOr {
			cond = &ast.UnaryExpr{Op: token.NOT, X: res}
		}
		body := sy
		if y != nil {
			body = append(body, assign(res, y))
		}
		stmts := append(sx, define(res, x), &ast.IfStmt{Cond: cond, Body: &ast.BlockStmt{List: body}})
		return stmts, res
	}
	stmts, xs := g.values([]syntax.Expr{e.X, e.Y})
	if xs == nil {
		return stmts, nil
	}
	return stmts, &ast.BinaryExpr{X: paren(xs[0]), Op: binaryOps[e.Op], Y: paren(xs[1])}
}

func (g *gen) callExpr(e *syntax.Call, args []ast.Expr) ast.Expr {
	if b := g.info.CallBuiltins[e]; b == check.BuiltinPrintln {
		g.usesFmt = true
		return &ast.CallExpr{Fun: &ast.SelectorExpr{X: ast.NewIdent("fmt"), Sel: ast.NewIdent("Println")}, Args: args}
	}
	fn := g.info.CallFuncs[e]
	return &ast.CallExpr{Fun: name(fn.Decl.Name), Args: args}
}

// effect lowers an expression evaluated only for its effect.
func (g *gen) effect(e syntax.Expr) []ast.Stmt {
	switch e := e.(type) {
	case *syntax.Call:
		stmts, args := g.values(e.Args)
		if args == nil {
			return stmts
		}
		return append(stmts, &ast.ExprStmt{X: g.callExpr(e, args)})
	case *syntax.If:
		return g.ifStmt(e, nil)
	case *syntax.Block:
		return []ast.Stmt{&ast.BlockStmt{List: g.blockInto(e, nil)}}
	case *syntax.Return:
		return g.returnStmt(e)
	}
	stmts, x := g.value(e)
	if x != nil {
		stmts = append(stmts, assign(ast.NewIdent("_"), x))
	}
	return stmts
}

// blockInto lowers a block's statements, assigning its tail value to
// res (or evaluating the tail for effect when res is nil).
func (g *gen) blockInto(b *syntax.Block, res *ast.Ident) []ast.Stmt {
	out := g.stmts(b.Stmts)
	if g.diverges(b.Stmts) {
		return out
	}
	if b.Tail != nil {
		if res == nil {
			out = append(out, g.effect(b.Tail)...)
		} else {
			stmts, x := g.value(b.Tail)
			out = append(out, stmts...)
			if x != nil {
				out = append(out, assign(res, x))
			}
		}
	}
	return out
}

// stmts lowers a block's statements (not its tail).
func (g *gen) stmts(list []syntax.Stmt) []ast.Stmt {
	var out []ast.Stmt
	for _, s := range list {
		switch s := s.(type) {
		case *syntax.Binding:
			stmts, x := g.value(s.Value)
			out = append(out, stmts...)
			if x == nil {
				return out
			}
			if g.info.Types[s.Value] == check.Int && isConst(x) {
				// An untyped Go constant would default to int, not int64.
				out = append(out, typedVar(name(s.Name), goType(check.Int), x))
			} else {
				out = append(out, define(name(s.Name), x))
			}
			if g.info.UnusedBindings[s] {
				out = append(out, assign(ast.NewIdent("_"), name(s.Name)))
			}
		case *syntax.ExprStmt:
			out = append(out, g.effect(s.X)...)
		}
	}
	return out
}

// blockReturn lowers a function body block whose tail is the function's
// result. A tail `if` or block becomes Go control flow that returns from
// each branch, which keeps the generated code close to hand-written Go.
func (g *gen) blockReturn(b *syntax.Block) []ast.Stmt {
	out := g.stmts(b.Stmts)
	if b.Tail == nil || g.diverges(b.Stmts) {
		return out
	}
	return append(out, g.tailReturn(b.Tail)...)
}

func (g *gen) tailReturn(e syntax.Expr) []ast.Stmt {
	switch e := e.(type) {
	case *syntax.If:
		if e.Else != nil {
			return g.ifChain(e, func(b *syntax.Block) []ast.Stmt { return g.blockReturn(b) })
		}
	case *syntax.Block:
		if len(e.Stmts) == 0 {
			if e.Tail == nil {
				return nil
			}
			return g.tailReturn(e.Tail)
		}
		return []ast.Stmt{&ast.BlockStmt{List: g.blockReturn(e)}}
	case *syntax.Return:
		return g.returnStmt(e)
	}
	stmts, x := g.value(e)
	if x == nil {
		return stmts
	}
	return append(stmts, &ast.ReturnStmt{Results: []ast.Expr{x}})
}

// diverges reports whether a statement list ends by never finishing.
func (g *gen) diverges(stmts []syntax.Stmt) bool {
	if len(stmts) == 0 {
		return false
	}
	if es, ok := stmts[len(stmts)-1].(*syntax.ExprStmt); ok {
		return g.info.Types[es.X] == check.Never
	}
	return false
}

// ifStmt lowers an if-expression. With res set, each branch assigns its
// value to res.
func (g *gen) ifStmt(e *syntax.If, res *ast.Ident) []ast.Stmt {
	return g.ifChain(e, func(b *syntax.Block) []ast.Stmt { return g.blockInto(b, res) })
}

// ifChain lowers an if/else-if/else chain, lowering each branch block
// with branch. An `else if` whose condition needs no setup statements
// becomes a Go `else if`.
func (g *gen) ifChain(e *syntax.If, branch func(*syntax.Block) []ast.Stmt) []ast.Stmt {
	stmts, cond := g.value(e.Cond)
	if cond == nil {
		return stmts
	}
	s := &ast.IfStmt{Cond: cond, Body: &ast.BlockStmt{List: branch(e.Then)}}
	switch els := e.Else.(type) {
	case *syntax.Block:
		s.Else = &ast.BlockStmt{List: branch(els)}
	case *syntax.If:
		rest := g.ifChain(els, branch)
		if len(rest) == 1 {
			s.Else = rest[0].(*ast.IfStmt)
		} else {
			s.Else = &ast.BlockStmt{List: rest}
		}
	}
	return append(stmts, s)
}

func (g *gen) returnStmt(e *syntax.Return) []ast.Stmt {
	if e.Value == nil {
		return []ast.Stmt{&ast.ReturnStmt{}}
	}
	stmts, x := g.value(e.Value)
	if x == nil {
		return stmts
	}
	return append(stmts, &ast.ReturnStmt{Results: []ast.Expr{x}})
}

// paren wraps operator expressions in parentheses, so nested operators
// keep bork's grouping regardless of Go's precedence rules.
func paren(x ast.Expr) ast.Expr {
	switch x.(type) {
	case *ast.BinaryExpr, *ast.UnaryExpr:
		return &ast.ParenExpr{X: x}
	}
	return x
}

// isConst reports whether x is a Go constant expression (literals and
// operators on them), which Go would give a default type.
func isConst(x ast.Expr) bool {
	switch x := x.(type) {
	case *ast.BasicLit:
		return true
	case *ast.ParenExpr:
		return isConst(x.X)
	case *ast.UnaryExpr:
		return isConst(x.X)
	case *ast.BinaryExpr:
		return isConst(x.X) && isConst(x.Y)
	}
	return false
}

func typedVar(id *ast.Ident, typ, value ast.Expr) ast.Stmt {
	return &ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{
		&ast.ValueSpec{Names: []*ast.Ident{id}, Type: typ, Values: []ast.Expr{value}},
	}}}
}

func define(lhs *ast.Ident, rhs ast.Expr) ast.Stmt {
	return &ast.AssignStmt{Lhs: []ast.Expr{lhs}, Tok: token.DEFINE, Rhs: []ast.Expr{rhs}}
}

func assign(lhs *ast.Ident, rhs ast.Expr) ast.Stmt {
	return &ast.AssignStmt{Lhs: []ast.Expr{lhs}, Tok: token.ASSIGN, Rhs: []ast.Expr{rhs}}
}

func varDecl(id *ast.Ident, typ ast.Expr) ast.Stmt {
	return &ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{
		&ast.ValueSpec{Names: []*ast.Ident{id}, Type: typ},
	}}}
}
