// StdValidatorArtifact derives native implementation code from the same typed
// library functions as comptime. Runtime source is type-checked alongside the
// artifact so call guards preserve single/multiple-result signatures.
func StdValidatorArtifact(files []*syntax.File, info *check.Info, runtimeSource []byte) ([]byte, error) {
	var instances []*check.ClassInstance
	for _, ci := range info.ClassInstances {
		if ci.Class.Prelude && ci.Class.Name == "InterpolationValidator" && strings.HasPrefix(ci.Pkg.Path, std.Prefix) && len(ci.TypeParams) == 0 && len(ci.Constraints) == 0 {
			instances = append(instances, ci)
		}
	}
	if len(instances) == 0 {
		return nil, fmt.Errorf("no concrete standard interpolation validators")
	}
	sort.Slice(instances, func(i, j int) bool {
		return instances[i].Pkg.Path+instances[i].Name < instances[j].Pkg.Path+instances[j].Name
	})

	// Unsupported standard validators remain ordinary comptime implementations.
	// Audit candidates independently so adding one cannot disable other artifacts.
	var accepted []*check.ClassInstance
	for _, ci := range instances {
		if _, err := stdValidatorArtifact(files, info, runtimeSource, []*check.ClassInstance{ci}); err == nil {
			accepted = append(accepted, ci)
		}
	}
	if len(accepted) == 0 {
		return []byte("// Code generated by genstdvalidators; DO NOT EDIT.\npackage stdvalidators\nfunc init(){descriptors=nil;nativeEvaluation=nil}\n"), nil
	}
	return stdValidatorArtifact(files, info, runtimeSource, accepted)
}

func stdValidatorArtifact(files []*syntax.File, info *check.Info, runtimeSource []byte, instances []*check.ClassInstance) ([]byte, error) {
	g := newGen(info)
	g.evalMode = true
	g.artifactMode = true
	g.comptimeMode = true
	var roots []*check.Func
	var cases, manifest strings.Builder
	goText := func(t check.Type) string {
		var b bytes.Buffer
		_ = printer.Fprint(&b, token.NewFileSet(), g.goType(t))
		return b.String()
	}
	var partsType, holeType, kindType, issueType string
	for index, ci := range instances {
		fn := ci.Methods[0]
		if len(fn.Needs) != 0 || fn.Effects != 0 || len(fn.TypeParams) != 0 || len(fn.ParamConstraints) != 0 && hasArtifactFacts(fn.ParamConstraints) {
			return nil, fmt.Errorf("unsupported validator %s", ci.Name)
		}
		if len(fn.Params) != 2 {
			return nil, fmt.Errorf("invalid validator signature")
		}
		parts := fn.Params[0].(*check.Record)
		hole := fn.Params[1].(*check.List).Elem.(*check.Record)
		kind := hole.Fields[0].Type.(*check.List).Elem.(*check.Sealed)
		issue := fn.Result.(*check.List).Elem.(*check.Record)
		partsType = goText(parts)
		holeType = goText(hole)
		kindType = goText(kind)
		issueType = goText(issue)
		roots = append(roots, fn)
		fmt.Fprintf(&cases, "case %d: return %s(%s{values:request.Parts},artifactHoles(request.Holes))\n", index, g.funcName(fn).Name, partsType)
		signature := ArtifactSignature(fn)
		var closure strings.Builder
		fmt.Fprintf(&closure, "artifact-abi-1/%s/%s/%s/%s\n", ci.Pkg.Path, ci.Name, ci.Type.String(), signature)
		closure.Write(runtimeSource)
		var sources strings.Builder
		for _, file := range files {
			if !file.Prelude && !strings.HasPrefix(file.Package, std.Prefix) {
				continue
			}
			digest := sha256.Sum256([]byte(file.Source))
			fmt.Fprintf(&sources, "{Path:%q,Digest:%q},", file.Path, fmt.Sprintf("%x", digest))
			fmt.Fprintf(&closure, "%s:%x\n", file.Path, digest)
		}
		var definitions strings.Builder
		var helperList []*check.Func
		for helper := range g.reachable([]*check.Func{fn}) {
			helperList = append(helperList, helper)
		}
		sort.Slice(helperList, func(i, j int) bool { return helperList[i].Decl.Pos.String() < helperList[j].Decl.Pos.String() })
		for _, helper := range helperList {
			encoded, err := ArtifactDefinition(helper)
			if err != nil {
				return nil, err
			}
			digest := sha256.Sum256(append(encoded, []byte(ArtifactSignature(helper))...))
			fmt.Fprintf(&definitions, "{Path:%q,Digest:%q},", helper.Decl.Pos.String(), fmt.Sprintf("%x", digest))
		}
		digest := sha256.Sum256([]byte(closure.String()))
		fmt.Fprintf(&manifest, "{Package:%q,Instance:%q,Builder:%q,Signature:%q,Identity:%q,Sources:[]Source{%s},Definitions:[]Source{%s}},", ci.Pkg.Path, ci.Name, ci.Type.String(), signature, fmt.Sprintf("%x", digest), sources.String(), definitions.String())
	}
	// Only pure, reviewed native dependencies are eligible for generation.
	allowed := map[string]bool{"fmt": true, "strconv": true, "strings": true, "bytes": true, "math": true, "unicode": true, "unicode/utf8": true}
	helpers := map[*check.Func]bool{}
	var visit func(*check.Func) error
	visit = func(fn *check.Func) error {
		if helpers[fn] {
			return nil
		}
		helpers[fn] = true
		if fn.Effects != 0 || len(fn.Needs) != 0 || fn.RuntimePackageReads || fn.TrackCaller || len(fn.TypeParams) != 0 {
			return fmt.Errorf("effectful/contextual artifact helper %s", fn.Decl.Name)
		}
		if fn.Decl.IsGo() {
			if fn.Decl.GoBody == nil {
				return fmt.Errorf("unsupported artifact Go binding %s", fn.Decl.Name)
			}
			for _, pkg := range fn.Decl.GoBody.Imports {
				if !allowed[pkg] {
					return fmt.Errorf("unsupported artifact Go import %s", pkg)
				}
			}
		}
		for _, callee := range append(append([]*check.Func(nil), fn.Calls...), goBodyFunctions(fn)...) {
			if err := visit(callee); err != nil {
				return err
			}
		}
		return nil
	}
	for _, fn := range roots {
		if err := visit(fn); err != nil {
			return nil, err
		}
	}
	encoder := &comptimeEncoder{g: g, names: map[check.Type]string{}}
	output := &check.List{Elem: instances[0].Methods[0].Result}
	entry, err := encoder.function(output)
	if err != nil {
		return nil, err
	}
	snippets := strings.Split(comptimeRuntime, "type _ctWriter")[0] + fmt.Sprintf(`
const (_ctSchemaVersion=%d;_ctResultLimit=%d;_ctNodeLimit=%d;_ctDepthLimit=%d)
func artifactHoles(values [][]Kind) []%s {
 out:=[]%s{}
 for _,values:=range values{
  kinds:=[]%s{}
  for _,value:=range values{
   switch value.Tag{
   case "Builtin":kinds=append(kinds,%s_Builtin{name:value.Name})
   case "Named":kinds=append(kinds,%s_Named{packagePath:value.PackagePath,name:value.Name})
   case "Unknown":kinds=append(kinds,%s_Unknown{})
   default:panic("invalid standard validator kind")
   }
  }
  out=append(out,%s{kinds:kinds})
 }
 return out
}
func artifactCall(index int,request Request) []%s {switch index{%s};panic("invalid artifact index")}
func init(){descriptors=[]Descriptor{%s};nativeEvaluation=func(calls []Call) []byte{
 _ctBudget=_ctResultLimit-128;_ctNodes=0
 values:=[][]%s{}
 for _,call:=range calls{values=append(values,artifactCall(call.Binding.index,call.Request))}
 data,err:=json.Marshal(struct{Version int;Value _ctValue}{_ctSchemaVersion,%s(values,0)})
 if err!=nil{panic(err)}
 if len(data)>_ctResultLimit{panic("comptime result exceeds 16 MiB")}
 return data
}}
`, check.ComptimeSchemaVersion, check.ComptimeResultLimit, check.ComptimeNodeLimit, check.ComptimeDepthLimit, holeType, holeType, kindType, kindType, kindType, kindType, holeType, issueType, cases.String(), manifest.String(), issueType, entry)
	parsed, err := parser.ParseFile(token.NewFileSet(), "", snippets, 0)
	if err != nil {
		return nil, err
	}
	g.extraFuncs = append(g.extraFuncs, parsed.Decls...)
	g.imports["encoding/json"] = true
	empty := &ast.FuncDecl{Name: ast.NewIdent("artifactUnusedMain"), Type: &ast.FuncType{Params: &ast.FieldList{}}, Body: &ast.BlockStmt{}}
	source, err := generate(g, files, roots, empty)
	if err != nil {
		return nil, err
	}
	var nativeFunctions []string
	for fn := range helpers {
		nativeFunctions = append(nativeFunctions, g.funcName(fn).Name)
	}
	return guardArtifact(source, runtimeSource, nativeFunctions...)
}
func hasArtifactFacts(values [][]*check.Constraint) bool {
	for _, v := range values {
		if len(v) > 0 {
			return true
		}
	}
	return false
}

// ArtifactDefinition omits the syntax back-reference to the owning instance.
func ArtifactDefinition(fn *check.Func) ([]byte, error) {
	decl := *fn.Decl
	decl.Instance = nil
	return json.Marshal(&decl)
}

func ArtifactSignature(fn *check.Func) string {
	var params []string
	for _, p := range fn.Params {
		params = append(params, p.String())
	}
	return "(" + strings.Join(params, ",") + ")->" + fn.Result.String()
}

func guardArtifact(source, runtimeSource []byte, nativeFunctions ...string) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "generated.go", source, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	file.Name.Name = "stdvalidators"
	// Artifact bytes must not depend on the generator working directory.
	for _, group := range file.Comments {
		kept := group.List[:0]
		for _, comment := range group.List {
			if !strings.HasPrefix(comment.Text, "/*line ") && !strings.HasPrefix(comment.Text, "//line ") {
				kept = append(kept, comment)
			}
		}
		group.List = kept
	}
	support, err := parser.ParseFile(fset, "runtime.go", runtimeSource, 0)
	if err != nil {
		return nil, err
	}
	ti := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Uses: map[*ast.Ident]types.Object{}}
	cfg := &types.Config{Importer: importer.Default()}
	pkg, err := cfg.Check("stdvalidators", fset, []*ast.File{file, support}, ti)
	if err != nil {
		return nil, fmt.Errorf("artifact typing: %w", err)
	}

	// Raw Go is limited to operations whose standard implementations are bounded
	// on metadata inputs. Unknown native calls are never admitted by import alone.
	nativeNames := map[string]bool{}
	for _, name := range nativeFunctions {
		nativeNames[name] = true
	}
	safeCalls := map[string]bool{"fmt.Sprintf": true, "strconv.Itoa": true, "strings.ContainsRune": true, "strings.Index": true, "strings.ReplaceAll": true, "strings.WriteString": true, "strings.WriteByte": true, "strings.String": true}
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || !nativeNames[fn.Name.Name] {
			continue
		}

		directNativeCalls := map[*ast.Ident]bool{}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			if call, ok := n.(*ast.CallExpr); ok {
				if selector, ok := call.Fun.(*ast.SelectorExpr); ok {
					directNativeCalls[selector.Sel] = true
				}
			}
			return true
		})
		var auditError error
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			if _, ok := n.(*ast.DeferStmt); ok {
				auditError = fmt.Errorf("unsupported native artifact defer")
				return false
			}
			if call, ok := n.(*ast.CallExpr); ok {
				if id, ok := call.Fun.(*ast.Ident); ok && (id.Name == "make" || id.Name == "new") {
					auditError = fmt.Errorf("unsupported native artifact allocation")
					return false
				}
			}

			switch node := n.(type) {
			case *ast.ArrayType:
				if node.Len != nil {
					auditError = fmt.Errorf("unsupported native array allocation")
					return false
				}
			case *ast.BinaryExpr:
				if basic, ok := ti.Types[node].Type.Underlying().(*types.Basic); ok && basic.Info()&types.IsString != 0 && node.Op == token.ADD {
					auditError = fmt.Errorf("unsupported native string growth")
					return false
				}
			case *ast.AssignStmt:
				if node.Tok == token.ADD_ASSIGN {
					for _, lhs := range node.Lhs {
						if basic, ok := ti.Types[lhs].Type.Underlying().(*types.Basic); ok && basic.Info()&types.IsString != 0 {
							auditError = fmt.Errorf("unsupported native string growth")
							return false
						}
					}
				}
			case *ast.UnaryExpr:
				if node.Op == token.AND {
					auditError = fmt.Errorf("unsupported native pointer allocation")
					return false
				}
			case *ast.CompositeLit:
				switch ti.Types[node].Type.Underlying().(type) {
				case *types.Map, *types.Array:
					auditError = fmt.Errorf("unsupported native aggregate allocation")
					return false
				}
			case *ast.CallExpr:
				if id, ok := node.Fun.(*ast.Ident); ok {
					if builtin, ok := ti.Uses[id].(*types.Builtin); ok {
						switch builtin.Name() {
						case "append", "cap", "len", "min", "max", "complex", "real", "imag", "copy", "clear", "delete", "panic", "recover":
						default:
							auditError = fmt.Errorf("unsupported native artifact builtin %s", builtin.Name())
							return false
						}
					}
				}
				if value, ok := ti.Types[node.Fun]; ok && value.IsType() {
					switch ti.Types[node].Type.Underlying().(type) {
					case *types.Slice, *types.Map, *types.Pointer:
						auditError = fmt.Errorf("unsupported native allocating conversion")
						return false
					}
				}

				if value, ok := ti.Types[node.Fun]; ok && value.IsType() && len(node.Args) == 1 {
					switch infoType := ti.Types[node.Args[0]].Type.Underlying().(type) {
					case *types.Slice, *types.Array:
						_ = infoType
						auditError = fmt.Errorf("unsupported native allocating conversion")
						return false
					}
				}
				if selector, ok := node.Fun.(*ast.SelectorExpr); ok {
					if fn, ok := ti.Uses[selector.Sel].(*types.Func); ok && fn.Pkg() != nil && fn.Pkg().Path() == "fmt" && fn.Name() == "Sprintf" {
						if _, err := artifactFormatCharge(node, ti); err != nil {
							auditError = err
							return false
						}
					}
				}
			}

			if id, ok := n.(*ast.Ident); ok {
				if f, ok := ti.Uses[id].(*types.Func); ok && f.Pkg() == pkg {
					// Typed dependencies are audited above. Unknown compiler formatting,
					// dictionary, or collection helpers are not eligible call edges.
					if (f.Parent() == pkg.Scope() || f.Type().(*types.Signature).Recv() != nil) && !nativeNames[f.Name()] {
						auditError = fmt.Errorf("unsupported generated artifact helper %s", f.Name())
						return false
					}
				}
			}
			if id, ok := n.(*ast.Ident); ok {
				if f, ok := ti.Uses[id].(*types.Func); ok && f.Pkg() != nil && f.Pkg() != pkg {
					key := f.Pkg().Path() + "." + f.Name()
					if receiver := f.Type().(*types.Signature).Recv(); receiver != nil {
						typ := receiver.Type()
						if pointer, ok := typ.(*types.Pointer); ok {
							typ = pointer.Elem()
						}
						named, ok := typ.(*types.Named)
						if !ok || named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != "strings" || named.Obj().Name() != "Builder" {
							auditError = fmt.Errorf("unsupported native artifact receiver")
							return false
						}
					}
					if !safeCalls[key] || !directNativeCalls[id] {
						auditError = fmt.Errorf("unsupported native artifact call %s", key)
						return false
					}
				}
			}
			return auditError == nil
		})
		if auditError != nil {
			return nil, auditError
		}
	}
	imports := map[string]string{}
	for _, imp := range file.Imports {
		path, _ := strconv.Unquote(imp.Path.Value)
		if imp.Name != nil {
			imports[path] = imp.Name.Name
		} else {
			imports[path] = path[strings.LastIndex(path, "/")+1:]
		}
	}
	qualifier := func(p *types.Package) string {
		if p == pkg {
			return ""
		}
		if alias := imports[p.Path()]; alias != "" {
			return alias
		}
		astutil.AddNamedImport(fset, file, p.Name(), p.Path())
		imports[p.Path()] = p.Name()
		return p.Name()
	}
	// Unknown blocking/scheduling forms are rejected, not approximated by guards.
	var rejected bool
	ast.Inspect(file, func(n ast.Node) bool {
		switch n.(type) {
		case *ast.GoStmt, *ast.SelectStmt, *ast.SendStmt, *ast.ChanType:
			rejected = true
		}
		if x, ok := n.(*ast.UnaryExpr); ok && x.Op == token.ARROW {
			rejected = true
		}
		return true
	})
	if rejected {
		return nil, fmt.Errorf("artifact contains unsupported blocking or scheduling operation")
	}
	var active []bool
	astutil.Apply(file, func(c *astutil.Cursor) bool {
		switch n := c.Node().(type) {
		case *ast.FuncDecl:
			active = append(active, n.Name.Name != "init")
		case *ast.FuncLit:
			active = append(active, true)
		}
		return true
	}, func(c *astutil.Cursor) bool {
		switch n := c.Node().(type) {
		case *ast.CallExpr:
			if len(active) == 0 || !active[len(active)-1] {
				return true
			}
			// Type conversions do not execute call edges; wrapping recover changes its
			// required direct-defer semantics. Both operations are intrinsically bounded.
			if tv, ok := ti.Types[n.Fun]; ok && tv.IsType() {
				return true
			}
			if id, ok := n.Fun.(*ast.Ident); ok && (id.Name == "recover" || id.Name == "panic") {
				return true
			}
			typ := ti.Types[n].Type
			var result string
			if tuple, ok := typ.(*types.Tuple); ok {
				var names []string
				for i := 0; i < tuple.Len(); i++ {
					names = append(names, types.TypeString(tuple.At(i).Type(), qualifier))
				}
				if len(names) > 0 {
					result = "(" + strings.Join(names, ",") + ")"
				}
			} else if typ != nil {
				result = types.TypeString(typ, qualifier)
			}
			expression, err := parser.ParseExpr("func() " + result + " { nativeStep(); }")
			if err != nil {
				panic(err)
			}

			// Buffer writes and appends can grow memory between loop guards. Capture
			// their arguments once, preserving evaluation order, and charge growth.
			allocation := ""
			captureCallee := false
			if id, ok := n.Fun.(*ast.Ident); ok && id.Name == "append" {
				allocation = strconv.Itoa(64 * (len(n.Args) - 1))
				if n.Ellipsis != token.NoPos {
					allocation = "64*len(_arg" + strconv.Itoa(len(n.Args)-1) + ")"
				}
			}
			if selector, ok := n.Fun.(*ast.SelectorExpr); ok {
				if fn, ok := ti.Uses[selector.Sel].(*types.Func); ok && fn.Pkg() != nil && fn.Pkg().Path() == "strings" {
					if fn.Name() == "ReplaceAll" {
						allocation = "nativeExpansion(len(_arg0),len(_arg2))"
						captureCallee = true
					}
					if fn.Name() == "WriteString" {
						allocation = "len(_arg0)"
						captureCallee = true
					}
					if fn.Name() == "WriteByte" {
						allocation = "1"
						captureCallee = true
					}
				}
			}
			if selector, ok := n.Fun.(*ast.SelectorExpr); ok {
				if fn, ok := ti.Uses[selector.Sel].(*types.Func); ok && fn.Pkg() != nil && fn.Pkg().Path() == "fmt" && fn.Name() == "Sprintf" {
					// Audited library formatting gets its exact conservative scalar bound.
					if charge, err := artifactFormatCharge(n, ti); err == nil {
						allocation = charge
						captureCallee = true
					}
				}
			}
			if allocation != "" {
				var parameters []string
				arguments := append([]ast.Expr(nil), n.Args...)
				inner := *n
				inner.Args = nil
				if captureCallee {
					parameters = append(parameters, "_callee "+types.TypeString(ti.Types[n.Fun].Type, qualifier))
					arguments = append([]ast.Expr{n.Fun}, arguments...)
					inner.Fun = ast.NewIdent("_callee")
				}
				for i, arg := range n.Args {
					name := "_arg" + strconv.Itoa(i)
					var argumentType types.Type
					if captureCallee {
						signature := ti.Types[n.Fun].Type.(*types.Signature)
						if signature.Variadic() && i >= signature.Params().Len()-1 {
							argumentType = types.Default(ti.Types[arg].Type)
						} else {
							argumentType = signature.Params().At(i).Type()
						}
					} else if i == 0 || n.Ellipsis != token.NoPos {
						argumentType = ti.Types[n].Type
					} else {
						argumentType = ti.Types[n].Type.(*types.Slice).Elem()
					}
					parameters = append(parameters, name+" "+types.TypeString(argumentType, qualifier))
					inner.Args = append(inner.Args, ast.NewIdent(name))
				}
				expression, err := parser.ParseExpr("func(" + strings.Join(parameters, ",") + ") " + result + "{nativeStep();nativeAllocate(" + allocation + ");}")
				if err != nil {
					panic(err)
				}
				closure := expression.(*ast.FuncLit)
				if result == "" {
					closure.Body.List = append(closure.Body.List, &ast.ExprStmt{X: &inner})
				} else {
					closure.Body.List = append(closure.Body.List, &ast.ReturnStmt{Results: []ast.Expr{&inner}})
				}
				c.Replace(&ast.CallExpr{Fun: closure, Args: arguments})
				return true
			}
			closure := expression.(*ast.FuncLit)
			if result == "" {
				closure.Body.List = append(closure.Body.List, &ast.ExprStmt{X: n})
			} else {
				closure.Body.List = append(closure.Body.List, &ast.ReturnStmt{Results: []ast.Expr{n}})
			}
			c.Replace(&ast.CallExpr{Fun: closure})

		case *ast.BlockStmt:
			// The shared comptime map runtime intentionally panics before its normal
			// implementation. Drop that dead implementation in the compiled artifact.
			if len(n.List) > 1 {
				if stmt, ok := n.List[0].(*ast.ExprStmt); ok {
					if call, ok := stmt.X.(*ast.CallExpr); ok {
						if id, ok := call.Fun.(*ast.Ident); ok && id.Name == "panic" {
							n.List = n.List[:1]
						}
					}
				}
			}
		case *ast.ForStmt:
			n.Body.List = append([]ast.Stmt{artifactStep()}, n.Body.List...)
		case *ast.RangeStmt:
			n.Body.List = append([]ast.Stmt{artifactStep()}, n.Body.List...)
		case *ast.FuncDecl:
			if active[len(active)-1] {
				n.Body.List = append(artifactEntry(), n.Body.List...)
			}
			active = active[:len(active)-1]
		case *ast.FuncLit:
			n.Body.List = append(artifactEntry(), n.Body.List...)
			active = active[:len(active)-1]
		}
		return true
	})
	var out bytes.Buffer
	out.WriteString("// Code generated by genstdvalidators; DO NOT EDIT.\n")
	if err := format.Node(&out, fset, file); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}
func artifactStep() ast.Stmt { return &ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("nativeStep")}} }
func artifactEntry() []ast.Stmt {
	return []ast.Stmt{&ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("nativeEnter")}}, &ast.DeferStmt{Call: &ast.CallExpr{Fun: ast.NewIdent("nativeLeave")}}}
}

// Only width-free, positional scalar formats enter the intrinsic. The charge is
// evaluated before fmt can allocate, using captured arguments exactly once.
func artifactFormatCharge(call *ast.CallExpr, info *types.Info) (string, error) {
	reject := func() (string, error) { return "", fmt.Errorf("unsupported native formatting arguments or format") }
	if call.Ellipsis != token.NoPos || len(call.Args) == 0 {
		return reject()
	}
	value := info.Types[call.Args[0]].Value
	if value == nil || value.Kind() != constant.String {
		return reject()
	}
	format := constant.StringVal(value)
	if len(format) > 4096 {
		return reject()
	}
	charges := []string{strconv.Itoa(len(format))}
	index := 1
	for i := 0; i < len(format); i++ {
		if format[i] != '%' {
			continue
		}
		i++
		if i >= len(format) {
			return reject()
		}
		if format[i] == '%' {
			continue
		}
		if index >= len(call.Args) {
			return reject()
		}
		basic, ok := types.Default(info.Types[call.Args[index]].Type).Underlying().(*types.Basic)
		if !ok {
			return reject()
		}
		switch format[i] {
		case 's':
			if basic.Info()&types.IsString == 0 {
				return reject()
			}
			charges = append(charges, "len(_arg"+strconv.Itoa(index)+")")
		case 'd':
			if basic.Info()&types.IsInteger == 0 {
				return reject()
			}
			charges = append(charges, "32")
		default:
			return reject()
		}
		index++
	}
	if index != len(call.Args) {
		return reject()
	}
	return strings.Join(charges, "+"), nil
}
